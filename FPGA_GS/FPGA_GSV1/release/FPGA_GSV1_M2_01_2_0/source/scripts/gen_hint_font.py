from pathlib import Path
from PIL import Image, ImageFont, ImageDraw
texts=['','KEY1 左转请求','KEY2 右转请求','KEY3 直行请求','KEY4 停车请求','KEY5 视角切换','KEY6 处理待接入','','','KEY1 停车优先请求未生效','KEY2 停车优先请求未生效','KEY3 停车优先请求未生效']
chars=sorted(set(''.join(texts)))
font=ImageFont.truetype('C:/Windows/Fonts/simsun.ttc',16)
s=['`timescale 1ns/1ps','// Fixed 16-pixel SimSun glyphs; generated by scripts/gen_hint_font.py.','module m1_key_osd(input [9:0] x,input [8:0] y,input visible,input [3:0] code,output area,pixel);',"wire [7:0] dx=x-10'd548; wire [3:0] row=y-9'd12;",'reg [5:0] glyph;reg [15:0] bits;',"assign area=visible && x>=548 && x<788 && y>=12 && y<28;",'assign pixel=area && bits[15-dx[3:0]];','always @* begin glyph=0; case({code,dx[7:4]})']
for c,text in enumerate(texts):
 for j,ch in enumerate(text):s.append(f"8'd{c*16+j}: glyph=6'd{chars.index(ch)+1};")
s+=['default:glyph=0;endcase end','always @* begin bits=0;case({glyph,row})']
for k,ch in enumerate(chars):
 im=Image.new('1',(16,16));ImageDraw.Draw(im).text((0,-2),ch,font=font,fill=1)
 for y in range(16):
  n=sum(im.getpixel((x,y))<<(15-x) for x in range(16))
  if n:s.append(f"10'd{(k+1)*16+y}:bits=16'h{n:04x};")
s+=['default:bits=0;endcase end','endmodule']
Path('rtl/display/m1_key_osd.v').write_text('\n'.join(s)+'\n',encoding='utf-8')
preview=Image.new('RGB',(800,200),'black');d=ImageDraw.Draw(preview)
for j,code in enumerate([1,2,3,4,5,6,9,10,11]):d.text((548,j*20),texts[code],font=font,fill='yellow')
preview.resize((1200,300)).save('reports/M1_02_hint_preview.png')
